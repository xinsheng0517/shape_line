function verifyExecutableRoute(route){
 const known=new Set(),available=new Set();
 const key=item=>JSON.stringify(item.units.map(u=>[u.id,u.sourceId,u.shapeKind,u.slot||u.quadrant,u.layer??0]).sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b))));
 const consume=items=>{
  const ids=new Set();
  for(const item of items){for(const unit of item.units){assert.equal(ids.has(unit.id),false,'one edge cannot consume a physical unit twice');ids.add(unit.id);}
   const identity=key(item);if(!available.has(identity)){assert.ok(item.units.every(u=>!known.has(u.id)),'a predecessor output must still be available before consumption');available.add(identity);item.units.forEach(u=>known.add(u.id));}
  }
  items.forEach(item=>available.delete(key(item)));
 };
 for(const step of route.steps){consume(step.inputs);for(const item of step.outputs||[step.output]){available.add(key(item));item.units.forEach(u=>known.add(u.id));}}
 consume([route.result]);
}
